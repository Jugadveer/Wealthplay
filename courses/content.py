"""
The course catalogue.

Content lives on disk at ``course_modules/<course>/<module>/{flash_cards,mcqs,qna}.json``.
This module is the only thing that reads it, and it is the store the mentor
resolves against.

Two problems this replaces:

* The catalogue was re-read from ~96 JSON files on every request. It is now
  parsed once and cached.
* A second, unrelated store (``financial_course.json``, four courses about chart
  patterns) was what the mentor searched. Since the real course ids were never
  in it, every question came back "Course 'investing-basics' not found."
"""

from __future__ import annotations

import json
import logging
import re
from functools import lru_cache
from pathlib import Path

from django.conf import settings

logger = logging.getLogger(__name__)

CONTENT_ROOT = Path(settings.BASE_DIR) / 'course_modules'

